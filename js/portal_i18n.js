class PortalI18n {
  constructor() {
    this.currentLang = localStorage.getItem('portal_lang') || 'en';
    
    const select = document.getElementById('portalLangSelect');
    if (select) {
      select.value = this.currentLang;
      select.addEventListener('change', (e) => {
        this.setLanguage(e.target.value);
      });
    }
    
    this.applyTranslations();
  }

  setLanguage(lang) {
    if (TRANSLATIONS[lang]) {
      this.currentLang = lang;
      localStorage.setItem('portal_lang', lang);
      this.applyTranslations();
    } else if (TRANSLATIONS.en) {
      // Fallback to English if es or ja are selected but not implemented
      this.currentLang = 'en';
      localStorage.setItem('portal_lang', 'en');
      this.applyTranslations();
    }
  }

  t(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  }

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.innerHTML = this.t(key);
      }
    });
  }
}

document.addEventListener('DOMContentLoaded', () => {
  new PortalI18n();
});
